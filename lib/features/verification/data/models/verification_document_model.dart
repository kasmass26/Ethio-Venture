import '../../domain/entities/verification_document_entity.dart';

/// Supabase-backed model for a row in [public.verification_documents].
///
/// Column mapping (DB → Dart):
///   id               → id
///   request_id       → requestId
///   user_id          → userId
///   storage_path     → storagePath
///   original_filename → originalFilename
///   mime_type        → mimeType
///   file_size_bytes  → fileSizeBytes
///   created_at       → createdAt
class VerificationDocumentModel extends VerificationDocumentEntity {
  const VerificationDocumentModel({
    required super.id,
    required super.requestId,
    required super.userId,
    required super.storagePath,
    required super.originalFilename,
    required super.mimeType,
    required super.fileSizeBytes,
    required super.createdAt,
  });

  factory VerificationDocumentModel.fromJson(Map<String, dynamic> json) {
    return VerificationDocumentModel(
      id: json['id'] as String,
      requestId: json['request_id'] as String,
      userId: json['user_id'] as String,
      storagePath: json['storage_path'] as String,
      originalFilename: json['original_filename'] as String,
      mimeType: json['mime_type'] as String,
      fileSizeBytes: (json['file_size_bytes'] as num).toInt(),
      createdAt: DateTime.parse(json['created_at'] as String),
    );
  }

  /// Insert payload — id and created_at are generated by the database.
  Map<String, dynamic> toInsertJson() {
    return {
      'request_id': requestId,
      'user_id': userId,
      'storage_path': storagePath,
      'original_filename': originalFilename,
      'mime_type': mimeType,
      'file_size_bytes': fileSizeBytes,
    };
  }
}
